import sys, time, subprocess, signal, os
sys.path.insert(0, ".")
from ptyssh import *
HCB = HC
def hc(*a): return subprocess.run([HCB] + list(a), capture_output=True, text=True)
def hdr(s): print("\n### " + s, flush=True)
def tail(s, n=160): return esc(s.data()[-n:], n * 3)
def rm(name): hc("kill", name); time.sleep(0.2); hc("rm", name)

os.makedirs(os.path.expanduser("~/work/s4"), exist_ok=True)
W = os.path.expanduser("~/work/s4")

hdr("exit: program exits 3 while attached")
rm("ex1"); hc("run", "--bg", "--no-parent", "--name", "ex1", "--cwd", W, "--", "sh", "-c", "sleep 1.5; echo bye; exit 3")
s = PtySSH(SSH + [attach_line("ex1")], 80, 24); rc = s.wait_exit(8)
print("  ssh rc=%s at %.3fs; tail=%s" % (rc, s.exit_t or -1, tail(s)))
hdr("exit: terminal killed (herdr-core kill) while attached")
rm("kl1"); hc("run", "--bg", "--no-parent", "--name", "kl1", "--cwd", W, "--", "sleep", "600")
s = PtySSH(SSH + [attach_line("kl1")], 80, 24); time.sleep(1.0)
t = time.monotonic(); hc("kill", "kl1"); rc = s.wait_exit(8)
print("  ssh rc=%s %.3fs after kill; tail=%s" % (rc, time.monotonic() - t, tail(s)))
hdr("exit: detached with ctrl+\\ (0x1c)")
rm("dt1"); hc("run", "--bg", "--no-parent", "--name", "dt1", "--cwd", W, "--", "sleep", "600")
s = PtySSH(SSH + [attach_line("dt1")], 80, 24); time.sleep(1.0)
t = time.monotonic(); s.write(b"\x1c"); rc = s.wait_exit(8)
print("  ssh rc=%s %.3fs after ^\\; tail=%s; core size now %s" % (rc, time.monotonic() - t, tail(s), get("dt1")))
hdr("exit: unknown terminal / finished terminal")
s = PtySSH(SSH + [attach_line("nope")], 80, 24); rc = s.wait_exit(8); print("  unknown: rc=%s tail=%s" % (rc, tail(s)))
s = PtySSH(SSH + [attach_line("ex1")], 80, 24); rc = s.wait_exit(8); print("  finished: rc=%s tail=%s" % (rc, tail(s)))
hdr("exit: herdr-core not installed (PATH without it) -> 127")
s = PtySSH(SSH + ["/bin/sh -c 'p=/nonexistent/herdr-core; [ -x \"$p\" ] || { echo \"herdr-core is not installed here\" >&2; exit 127; }'"], 80, 24)
rc = s.wait_exit(8); print("  rc=%s tail=%s" % (rc, tail(s)))

hdr("two attaches from two ssh sessions at once (sizes seen by core)")
rm("two"); hc("run", "--bg", "--no-parent", "--name", "two", "--cwd", W, "--", "sh", "-c", "trap 'echo SIZE $(stty size)' WINCH; echo SIZE $(stty size); while :; do sleep 0.2; done")
A = PtySSH(SSH + [attach_line("two")], 80, 24); time.sleep(0.8); print("  A(80x24) attached           ->", get("two"))
B = PtySSH(SSH + [attach_line("two")], 52, 28); time.sleep(0.8); print("  B(52x28) attached           ->", get("two"))
A.write(b"a"); time.sleep(0.5); print("  A types                     ->", get("two"))
B.write(b"b"); time.sleep(0.5); print("  B types                     ->", get("two"))
B.setsize(60, 30); dt = wait_size("two", (60, 30)); print("  B resize 60x30              ->", get("two"), "after", dt)
B.close_master(); B.wait_exit(3); time.sleep(0.4); print("  B ssh gone                  ->", get("two"))
A.close_master(); A.wait_exit(3); time.sleep(0.4); print("  A ssh gone                  ->", get("two"))
print("  program saw (read screen):", repr(hc("read", "two").stdout[-120:]))

hdr("vim-tiny (alt screen) attach")
open(W + "/note.txt", "w").write("line one\nline two\n")
rm("vi1"); r = hc("run", "--bg", "--no-parent", "--name", "vi1", "--cwd", W, "--", "vi", "-u", "NONE", "-N", W + "/note.txt")
time.sleep(0.8)
s = PtySSH(SSH + [attach_line("vi1")], 100, 30); time.sleep(1.5)
d = s.data()
print("  first paint @%s s; bytes=%d; core size=%s" % (s.first(b"\x1b[!p"), len(d), get("vi1")))
print("  contains ESC[?1049h (alt screen):", b"\x1b[?1049h" in d, "| contains 'line one':", b"line one" in d)
print("  chunks (t,len):", [(round(t, 3), len(c)) for t, c in s.chunks])
n0 = len(s.chunks); t = time.monotonic(); s.setsize(60, 20); dt = wait_size("vi1", (60, 20)); time.sleep(0.6)
print("  resize 60x20: core saw after %s s; bytes after resize: %d; vim redraw chunk starts: %s" % (dt, sum(len(c) for _, c in s.chunks[n0:]), esc(b"".join(c for _, c in s.chunks[n0:])[:160])))
s.write(b":q!\r"); time.sleep(0.8)
print("  after :q! -> ssh rc=%s tail=%s" % (s.wait_exit(3), tail(s)))
print("  record:", hc("get", "vi1").stdout[:200].replace("\n", " "))
