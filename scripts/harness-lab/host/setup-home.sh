#!/bin/sh
# Build step, as waycar: apply the per-harness mock configuration and create
# the demo project. Each /opt/harness-lab/config/<kind>/ may hold
#   home/      files copied into ~ as they are
#   env        KEY=VALUE lines exported to every shell (~/.config/harness-lab/env.sh)
#   setup.sh   run after the files are in place (configuration a CLI writes itself)
set -eu
config=/opt/harness-lab/config
demo=$HOME/work/demo

# The lab environment comes first in ~/.bashrc, ahead of Ubuntu's
# non-interactive return, so `ssh host cmd` gets it too.
env_sh=$HOME/.config/harness-lab/env.sh
mkdir -p "$(dirname "$env_sh")"
{
  echo '# Generated by scripts/harness-lab/host/setup-home.sh from config/*/env.'
  echo 'export PATH="$HOME/.local/bin:$HOME/.npm-global/bin:$HOME/.opencode/bin:$HOME/.grok/bin:$HOME/.bun/bin:$PATH"'
  echo 'export LANG=C.UTF-8 LC_ALL=C.UTF-8'
  for f in "$config"/*/env; do
    [ -f "$f" ] || continue
    echo "# $(basename "$(dirname "$f")")"
    sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*=.*\)$/export \1/p' "$f"
  done
} >"$env_sh"
if ! grep -q 'harness-lab/env.sh' "$HOME/.bashrc"; then
  { echo '. "$HOME/.config/harness-lab/env.sh"'; cat "$HOME/.bashrc"; } >"$HOME/.bashrc.new"
  mv "$HOME/.bashrc.new" "$HOME/.bashrc"
fi
. "$env_sh"

git config --global user.name 'Waycar Lab'
git config --global user.email 'lab@waycar.invalid'
git config --global init.defaultBranch main
if [ ! -d "$demo/.git" ]; then
  mkdir -p "$demo"
  printf '# demo\n\nScratch project for the Waycar harness lab.\n' >"$demo/README.md"
  git -C "$demo" init -q
  git -C "$demo" add README.md
  git -C "$demo" commit -qm 'Initial commit'
fi

for dir in "$config"/*/; do
  kind=$(basename "$dir")
  if [ -d "$dir/home" ]; then
    cp -R "$dir/home/." "$HOME/"
  fi
  if [ -f "$dir/setup.sh" ]; then
    echo "harness-lab: configuring $kind"
    sh "$dir/setup.sh"
  fi
done
