HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def num(value: float) -> str:
    """Shortest decimal for a token number: 18 -> "18", 0.045 -> "0.045"."""
    return f"{value:g}"


def px(value: float) -> str:
    return "0" if value == 0 else f"{num(value)}px"


def camel(name: str) -> str:
    head, *rest = name.split("-")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def shadow_swift_name(name: str) -> str:
    # Some CI runners still have Python 3.8: no str.removeprefix.
    prefix = "shadow-"
    return camel(name[len(prefix):] if name.startswith(prefix) else name)


def fluid(size: float | dict) -> str:
    if isinstance(size, dict):
        return f"clamp({px(size['min'])}, {size['fluid']}, {px(size['max'])})"
    return px(size)


def check_notes(value: object, path: str = "tokens") -> None:
    """Notes land verbatim in a CSS comment, a DESIGN.md table cell and a
    Swift doc comment, so reject anything that would end one early."""
    if isinstance(value, dict):
        for key, child in value.items():
            if key == "note" and isinstance(child, str):
                for bad, where in (("*/", "a CSS comment"), ("|", "a DESIGN.md table cell"), ("\n", "a doc comment")):
                    if bad in child:
                        fail(f"{path}.note: {bad!r} would break {where}")
            else:
                check_notes(child, f"{path}.{key}")
    elif isinstance(value, list):
        for index, child in enumerate(value):
            check_notes(child, f"{path}[{index}]")


class Tokens:
    def __init__(self, data: dict) -> None:
        self.data = data
        self.colors: dict = data["color"]
        for name, token in self.colors.items():
            if not HEX.match(token["value"]):
                fail(f"color {name}: value must be #rrggbb, got {token['value']!r}")
            if "light" in token:
                if not HEX.match(token["light"]):
                    fail(f"color {name}: light must be #rrggbb, got {token['light']!r}")
                if "alpha" in token:
                    fail(f"color {name}: light and alpha cannot be combined")
        self.status: dict = data["status"]
        fallbacks = [name for name, hue in self.status.items() if hue.get("fallback")]
        if len(fallbacks) != 1:
            fail(f"status: exactly one hue needs \"fallback\": true, found {fallbacks}")
        mapped: set[str] = set()
        for name, hue in self.status.items():
            for role in ("wash", "ink"):
                for flavour in ("mocha", "latte"):
                    if not HEX.match(hue[role][flavour]):
                        fail(f"status {name}: {role}.{flavour} must be #rrggbb, got {hue[role][flavour]!r}")
            for status in hue["statuses"]:
                if status in mapped:
                    fail(f"status {name}: {status!r} is already mapped to another hue")
                mapped.add(status)
        for name in WATCH_COLORS:
            if name not in self.colors:
                fail(f"color {name}: needed by WatchBrand.Colors")
        for name in WATCH_RADII:
            if name not in data["radius"]:
                fail(f"radius {name}: needed by WatchBrand.Radii")
        check_notes(data)

    def channels(self, ref: str) -> tuple[int, int, int]:
        """RGB channels of a color token name or a literal #rrggbb."""
        if ref.startswith("#"):
            if not HEX.match(ref):
                fail(f"bad color literal {ref!r}")
            value = ref
        elif ref in self.colors:
            value = self.colors[ref]["value"]
        else:
            fail(f"unknown color token {ref!r}")
        return tuple(int(value[i : i + 2], 16) for i in (1, 3, 5))  # type: ignore[return-value]

    def alpha(self, ref: str, override: float | None) -> float | None:
        if override is not None:
            return override
        return None if ref.startswith("#") else self.colors[ref].get("alpha")

    def css_color(self, ref: str, alpha: float | None = None) -> str:
        r, g, b = self.channels(ref)
        a = self.alpha(ref, alpha)
        if a is None:
            return f"#{r:02x}{g:02x}{b:02x}"
        return f"rgb({r} {g} {b} / {num(a)})"


# ---------- CSS ----------


def css_gradient(tokens: Tokens, gradient: dict) -> str:
    stops = []
    for stop in gradient["stops"]:
        color = tokens.css_color(stop["color"], stop.get("alpha"))
        stops.append(f"{color} {num(stop['at'])}%" if "at" in stop else color)
    return f"linear-gradient({num(gradient['angle'])}deg, {', '.join(stops)})"


def css_shadow(tokens: Tokens, shadow: dict) -> str:
    layers = []
    for layer in shadow["layers"]:
        parts = ["inset"] if layer.get("inset") else []
        parts += [px(layer.get("x", 0)), px(layer.get("y", 0)), px(layer.get("blur", 0))]
        if layer.get("spread", 0):
            parts.append(px(layer["spread"]))
        parts.append(tokens.css_color(layer["color"], layer.get("alpha")))
        layers.append(" ".join(parts))
    return ", ".join(layers)


def generate_css(tokens: Tokens) -> str:
    data = tokens.data
    out = [
        "/*",
        f" * {GENERATED_BY}",
        " * Change the JSON and rerun the script; DESIGN.md explains every token.",
        " * Each opaque color has a `-rgb` twin of bare channels for tints:",
        " * rgb(var(--violet-rgb) / 0.35).",
        " */",
        "",
        ":root {",
        f"  color-scheme: {data['scheme']};",
        "",
        "  /* Color */",
    ]
    for name, token in tokens.colors.items():
        out.append(f"  --{name}: {tokens.css_color(name)}; /* {token['note']} */")
        if "alpha" not in token:
            out.append(f"  --{name}-rgb: {' '.join(str(c) for c in tokens.channels(name))};")

    out += ["", "  /* Gradient */"]
    for name, gradient in data["gradient"].items():
        out.append(f"  --{name}: {css_gradient(tokens, gradient)}; /* {gradient['note']} */")

    out += ["", "  /* Shadow */"]
    for name, shadow in data["shadow"].items():
        out.append(f"  --{name}: {css_shadow(tokens, shadow)}; /* {shadow['note']} */")

    out += ["", "  /* Radius */"]
    for name, radius in data["radius"].items():
        out.append(f"  --radius-{name}: {px(radius['value'])}; /* {radius['note']} */")

    out += ["", "  /* Space */"]
    for name, space in data["space"].items():
        out.append(f"  --{name}: {fluid(space if 'min' in space else space['value'])}; /* {space['note']} */")

    out += ["", "  /* Font */"]
    for name, font in data["font"].items():
        out.append(f"  --font-{name}: {', '.join(font['stack'])};")

    out += ["", "  /* Type: size, weight, leading, tracking */"]
    for name, style in data["type"].items():
        out.append(f"  --fs-{name}: {fluid(style['size'])}; /* {style['note']} */")
        if "weight" in style:
            out.append(f"  --fw-{name}: {num(style['weight'])};")
        if "leading" in style:
            out.append(f"  --lh-{name}: {num(style['leading'])};")
        if "tracking" in style:
            out.append(f"  --ls-{name}: {num(style['tracking'])}em;")
    out.append("}")

    compact = data["breakpoint"]["compact"]
    overrides = [(name, space["compact"]) for name, space in data["space"].items() if "compact" in space]
    if overrides:
        out += ["", f"/* {compact['note']} */", f"@media (max-width: {px(compact['value'])}) {{", "  :root {"]
        out += [f"    --{name}: {px(value)};" for name, value in overrides]
        out += ["  }", "}"]
    return "\n".join(out) + "\n"


# ---------- TypeScript ----------


def generate_ts(tokens: Tokens) -> str:
    out = [
        f"// {GENERATED_BY}",
        "// For values CSS cannot reach, such as <meta name=\"theme-color\">. Styles use tokens.css.",
        "",
        "export const color = {",
    ]
    for name in tokens.colors:
        out.append(f"  {camel(name)}: '{tokens.css_color(name)}',")
    out += ["} as const;", ""]
    return "\n".join(out)


# ---------- Swift ----------


def swift_color(tokens: Tokens, ref: str, alpha: float | None = None) -> str:
    if ref.startswith("#"):
        base = f"brandRGB(0x{ref[1:].upper()})"
        return base if alpha is None else f"brandRGB(0x{ref[1:].upper()}, opacity: {num(alpha)})"
    base = f"Colors.{camel(ref)}"
    return base if alpha is None else f"{base}.opacity({num(alpha)})"


def unit_points(angle: float) -> tuple[str, str]:
    """CSS gradient angle (0deg points up, clockwise) to SwiftUI start/end points."""
    radians = math.radians(angle)
    dx, dy = math.sin(radians) / 2, -math.cos(radians) / 2

    def point(x: float, y: float) -> str:
        return f"UnitPoint(x: {num(round(x, 3) + 0.0)}, y: {num(round(y, 3) + 0.0)})"

    return point(0.5 - dx, 0.5 - dy), point(0.5 + dx, 0.5 + dy)


def swift_stops(tokens: Tokens, stops: list[dict]) -> list[tuple[str, float]]:
    """Stops as (Swift color, location), with CSS's implicit and out-of-range
    positions resolved so every location sits in 0...1."""
    count = len(stops)
    if count < 2:
        fail("a gradient needs at least two stops")
    located = []
    for index, stop in enumerate(stops):
        at = stop.get("at", 0 if index == 0 else 100 if index == count - 1 else None)
        if at is None:
            fail("a middle gradient stop needs an explicit `at`")
        located.append((stop, at / 100))

    def rgba(stop: dict) -> tuple[float, float, float, float]:
        r, g, b = tokens.channels(stop["color"])
        a = tokens.alpha(stop["color"], stop.get("alpha"))
        return r, g, b, 1.0 if a is None else a

    result = []
    for index, (stop, location) in enumerate(located):
        if 0 <= location <= 1:
            result.append((swift_color(tokens, stop["color"], stop.get("alpha")), location))
            continue
        # Clip an out-of-range stop to the edge, taking the color the CSS
        # gradient actually shows there.
        neighbor_index = index - 1 if location > 1 else index + 1
        if not 0 <= neighbor_index < count:
            fail(f"gradient stop at {num(location * 100)}% has no neighbor inside 0...100%")
        neighbor, neighbor_location = located[neighbor_index]
        edge = 1.0 if location > 1 else 0.0
        t = (edge - neighbor_location) / (location - neighbor_location)
        mixed = [n + (s - n) * t for n, s in zip(rgba(neighbor), rgba(stop))]
        hex_value = "".join(f"{round(c):02X}" for c in mixed[:3])
        opacity = round(mixed[3], 3)
        color = f"brandRGB(0x{hex_value})" if opacity == 1 else f"brandRGB(0x{hex_value}, opacity: {num(opacity)})"
        result.append((color, edge))
    return result


def doc(note: str, indent: str) -> str:
    return f"{indent}/// {note}"


def generate_swift(tokens: Tokens) -> str:
    data = tokens.data
    i1, i2, i3 = "    ", "        ", "            "
    out = [
        f"// {GENERATED_BY}",
        "// Change the JSON and rerun the script; DESIGN.md explains every token and where it belongs.",
        "",
        "import SwiftUI",
        "",
        "/// Waycar's brand tokens. waycar.dev reads the same values from apps/web/src/styles/tokens.css.",
        "enum Brand {",
        f"{i1}/// waycar.dev is {data['scheme']} only, so there is one value per token. Branded surfaces",
        f"{i1}/// (What's New) pin this scheme; everyday app chrome follows the system.",
        f"{i1}static let colorScheme: ColorScheme = .{data['scheme']}",
        "",
        f"{i1}enum Colors {{",
    ]
    for name, token in tokens.colors.items():
        value = token["value"][1:].upper()
        alpha = token.get("alpha")
        if "light" in token:
            light = token["light"][1:].upper()
            call = f"Color(uiColor: UIColor {{ $0.userInterfaceStyle == .dark ? brandUIRGB(0x{value}) : brandUIRGB(0x{light}) }})"
        else:
            call = f"brandRGB(0x{value})" if alpha is None else f"brandRGB(0x{value}, opacity: {num(alpha)})"
        out += [doc(token["note"], i2), f"{i2}static let {camel(name)} = {call}"]
    out += [f"{i1}}}", "", f"{i1}enum Gradients {{"]
    for name, gradient in data["gradient"].items():
        start, end = unit_points(gradient["angle"])
        out += [doc(gradient["note"], i2), f"{i2}static var {camel(name)}: LinearGradient {{", f"{i3}LinearGradient("]
        out.append(f"{i3}    stops: [")
        for color, location in swift_stops(tokens, gradient["stops"]):
            out.append(f"{i3}        .init(color: {color}, location: {num(round(location, 4))}),")
        out += [f"{i3}    ],", f"{i3}    startPoint: {start},", f"{i3}    endPoint: {end})", f"{i2}}}"]
    out += [f"{i1}}}", ""]

    out += [
        f"{i1}/// Text styles keep Dynamic Type. The web sizes live in tokens.json; the app maps each",
        f"{i1}/// style to the nearest SwiftUI text style.",
        f"{i1}enum Fonts {{",
    ]
    for name, font in data["font"].items():
        out += [doc(font["note"], i2), f"{i2}static let {camel(name)}Design: Font.Design = .{font['swift']}"]
    tracking = []
    for name, style in data["type"].items():
        swift = style["swift"]
        if swift["style"] not in SWIFT_TEXT_STYLE_SIZES:
            fail(f"type {name}: unknown SwiftUI text style {swift['style']!r}")
        if swift["weight"] not in SWIFT_WEIGHTS:
            fail(f"type {name}: unknown SwiftUI weight {swift['weight']!r}")
        design = data["font"][style["family"]]["swift"]
        out += [
            doc(style["note"], i2),
            f"{i2}static var {camel(name)}: Font {{ .system(.{swift['style']}, design: .{design}, weight: .{swift['weight']}) }}",
        ]
        if "tracking" in style:
            points = round(style["tracking"] * SWIFT_TEXT_STYLE_SIZES[swift["style"]], 2) + 0.0
            tracking.append((name, style["tracking"], swift["style"], points))
    out += [f"{i1}}}", ""]

    out += [f"{i1}/// Letter spacing in points for `.tracking(_:)`, from the web's em values.", f"{i1}enum Tracking {{"]
    for name, em, text_style, points in tracking:
        out += [
            doc(f"{num(em)} em at {text_style}'s default size.", i2),
            f"{i2}static let {camel(name)}: CGFloat = {num(points)}",
        ]
    out += [f"{i1}}}", "", f"{i1}enum Radius {{"]
    for name, radius in data["radius"].items():
        out += [doc(radius["note"], i2), f"{i2}static let {camel(name)}: CGFloat = {num(radius['value'])}"]
    out += [f"{i1}}}", "", f"{i1}enum Spacing {{"]
    for name, space in data["space"].items():
        swift_name = space.get("swiftName", camel(name))
        out.append(doc(space["note"], i2))
        if "min" in space:
            out.append(f"{i2}static let {swift_name}Min: CGFloat = {num(space['min'])}")
            out.append(f"{i2}static let {swift_name}Max: CGFloat = {num(space['max'])}")
            continue
        out.append(f"{i2}static let {swift_name}: CGFloat = {num(space['value'])}")
        if "compact" in space:
            out.append(f"{i2}static let {swift_name}Compact: CGFloat = {num(space['compact'])}")
    out += [f"{i1}}}", ""]

    out += [
        f"{i1}/// Drop-shadow layers. SwiftUI has no spread or inset shadow, so rings and inset",
        f"{i1}/// layers stay web-only and radius is half the CSS blur. Apply with `.brandShadow(_:)`.",
        f"{i1}enum Shadows {{",
    ]
    for name, shadow in data["shadow"].items():
        layers = [
            layer
            for layer in shadow["layers"]
            if not layer.get("inset") and layer.get("blur", 0) > 0
        ]
        if not layers:
            continue
        out += [doc(shadow["note"], i2), f"{i2}static let {shadow_swift_name(name)}: [BrandShadow] = ["]
        for layer in layers:
            color = swift_color(tokens, layer["color"], layer.get("alpha"))
            out.append(
                f"{i3}BrandShadow(color: {color}, radius: {num(layer['blur'] / 2)}, "
                f"x: {num(layer.get('x', 0))}, y: {num(layer.get('y', 0))}),"
            )
        out.append(f"{i2}]")
    out += [f"{i1}}}", ""]

    glass = data["glass"]
    out += [
        doc(glass["note"], i1),
        f"{i1}enum Glass {{",
        f"{i2}static var fill: LinearGradient {{ Gradients.{camel(glass['fill'])} }}",
        f"{i2}static let stroke = Colors.{camel(glass['stroke'])}",
        f"{i2}static let radius = Radius.{camel(glass['radius'])}",
        f"{i1}}}",
        "}",
        "",
        "/// One drop-shadow layer of a brand shadow token.",
        "struct BrandShadow: Sendable {",
        "    let color: Color",
        "    let radius: CGFloat",
        "    let x: CGFloat",
        "    let y: CGFloat",
        "}",
        "",
        "extension View {",
        "    /// Applies every layer of a `Brand.Shadows` token, first layer innermost.",
        "    func brandShadow(_ layers: [BrandShadow]) -> some View {",
        "        modifier(BrandShadowModifier(layers: layers))",
        "    }",
        "",
        "    /// The glass card from waycar.dev: faint white fill, hairline border, continuous corners.",
        "    func brandGlass() -> some View {",
        "        let shape = RoundedRectangle(cornerRadius: Brand.Glass.radius, style: .continuous)",
        "        return background(Brand.Glass.fill, in: shape)",
        "            .overlay(shape.strokeBorder(Brand.Glass.stroke, lineWidth: 1))",
        "    }",
        "}",
        "",
        "private struct BrandShadowModifier: ViewModifier {",
        "    let layers: [BrandShadow]",
        "",
        "    func body(content: Content) -> some View {",
        "        layers.reduce(AnyView(content)) { view, layer in",
        "            AnyView(view.shadow(color: layer.color, radius: layer.radius, x: layer.x, y: layer.y))",
        "        }",
        "    }",
        "}",
        "",
        "private func brandRGB(_ hex: UInt32, opacity: Double = 1) -> Color {",
        "    Color(",
        "        .sRGB,",
        "        red: Double((hex >> 16) & 0xFF) / 255,",
        "        green: Double((hex >> 8) & 0xFF) / 255,",
        "        blue: Double(hex & 0xFF) / 255,",
        "        opacity: opacity)",
        "}",
    ]
    if any("light" in token for token in tokens.colors.values()):
        out += [
            "",
            "private func brandUIRGB(_ hex: UInt32) -> UIColor {",
            "    UIColor(",
            "        red: CGFloat((hex >> 16) & 0xFF) / 255,",
            "        green: CGFloat((hex >> 8) & 0xFF) / 255,",
            "        blue: CGFloat(hex & 0xFF) / 255,",
            "        alpha: 1)",
            "}",
        ]
    return "\n".join(out) + "\n"


def swift_hex(value: str) -> str:
    """`#89b4fa` -> `0x89B4FA`."""
    return f"0x{value[1:].upper()}"


def status_label(hue: dict) -> str:
    """The raw statuses a hue paints, in prose: "blocked", "idle, and any other status"."""
    statuses = ", ".join(hue["statuses"])
    if not hue.get("fallback"):
        return statuses
    return f"{statuses}, and any other status" if statuses else "any other status"


