#!/usr/bin/env python3
"""Generate Waycar's brand tokens for the web and the app from design/tokens.json.

Usage:
    scripts/generate-brand-tokens.py            # rewrite the generated files
    scripts/generate-brand-tokens.py --check    # fail if a committed output is stale

Outputs:
    apps/web/src/styles/tokens.css                  CSS custom properties (global.css imports it)
    apps/web/src/styles/tokens.ts                   color constants for places CSS cannot reach
    Sources/Waycar/Design/BrandTokens.swift         `Brand` colors, gradients, fonts, radii, shadows
    DESIGN.md                                       the token tables between the GENERATED TOKENS markers
    Sources/Waycar/Design/Brand.xcassets            the AccentColor colorset, from the `accent` token
    Sources/WaycarActivityCore/StatusPaletteTokens.swift
                                                    the Agent status palette as platform-neutral 0xRRGGBB
                                                    constants (app Console, Live Activity, watch)
    Sources/WaycarWatch/Design/WatchBrandTokens.swift
                                                    `WatchBrand`: the dark-only colors, status colors and
                                                    radii the watch app uses
    Sources/WaycarWatch/Resources/Assets.xcassets/AccentColor.colorset
                                                    the watch AccentColor, the `accent` dark value

A color token may carry `"light": "#rrggbb"` next to `"value"` (the dark value):
the app gets a light/dark dynamic color, the dark-only web gets `value`.

A `status` hue maps raw Agent status values to a wash (capsule fills) and an ink
(text and dots), each in herdr's Catppuccin Mocha (dark) and Latte (light). One
hue is the `fallback` for every status no other hue lists.

design/tokens.json is the only place a brand value lives; DESIGN.md explains the
tokens and where each one belongs. Every opaque color also gets a `--<name>-rgb`
twin holding bare channels, so tints stay token-driven:
`rgb(var(--violet-rgb) / 0.35)`.

The output is deterministic (token order follows the JSON, no timestamps), so
rerunning against unchanged tokens is a no-op diff.
"""

